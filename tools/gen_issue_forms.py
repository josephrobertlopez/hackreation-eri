#!/usr/bin/env python3
"""Generate one GitHub issue form per ERI project, from the backlog.

An attempt declares which of ERI's requirements it is claiming. If those IDs
are typed by hand into a free-text box, they get typed wrong, and a reviewer
comparing two attempts at the same project ends up comparing two different
vocabularies. So the form lists every ID as a checkbox, and the list comes from
docs/eri-backlog.json -- which comes from ERI's own document.

Generated, because 47 checkboxes hand-maintained across four files drift from
the backlog the first time ERI edits a table, and drift silently.

    python3 tools/gen_issue_forms.py            # write the forms
    python3 tools/gen_issue_forms.py --check    # fail if they are stale

YAML is emitted with json.dumps() for every scalar. JSON is a subset of YAML,
so a double-quoted JSON string is always a valid YAML scalar, and ERI's text
contains quotes, colons and ellipses that a hand-rolled quoter gets wrong. It
also means this script needs no YAML library: a runner's python3 is not
guaranteed to have PyYAML, and a gate that cannot run is a gate that gets
deleted.

`config.yml` carries absolute URLs, which cannot be written without knowing the
owner and repository. Those are DERIVED at generation time from
$GITHUB_REPOSITORY, else from the `origin` remote, and never hardcoded -- a
generated copy of this template re-derives its own. config.yml is therefore
excluded from --check: its correct content depends on where the repository
lives, not on what the backlog says.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BACKLOG = os.path.join("docs", "eri-backlog.json")
OUTDIR = os.path.join(".github", "ISSUE_TEMPLATE")
SOURCE_DOC = "docs/eri-problem-statements.md"
CONFIG = os.path.join(OUTDIR, "config.yml")

HEADER = (
    "# Generated by tools/gen_issue_forms.py from " + BACKLOG + ".\n"
    "# Do not edit by hand -- regenerate, or the claimable IDs drift away\n"
    "# from ERI's own document.\n"
)

# ERI's three hard prohibitions. Required on every attempt, every project.
PROHIBITIONS = [
    "No field, question or required step asks for a disability or diagnosis.",
    "Nothing scores or ranks candidates.",
    "Nothing makes an automated hiring or accommodation decision — a person decides.",
]


def q(value) -> str:
    """A scalar as valid YAML, via JSON."""
    return json.dumps(value, ensure_ascii=False)


def repo_slug() -> str:
    """owner/repo from the Actions context or the git remote. Never a literal."""
    env = os.environ.get("GITHUB_REPOSITORY", "").strip()
    if re.fullmatch(r"[\w.-]+/[\w.-]+", env):
        return env
    try:
        url = subprocess.run(["git", "remote", "get-url", "origin"],
                             capture_output=True, text=True, check=True,
                             cwd=REPO).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""
    m = re.search(r"[:/]([\w.-]+)/([\w.-]+?)(?:\.git)?/?$", url)
    return f"{m.group(1)}/{m.group(2)}" if m else ""


def checkbox_block(bid: str, label: str, desc: str, items: list[dict]) -> list[str]:
    out = ["  - type: checkboxes",
           f"    id: {bid}",
           "    attributes:",
           f"      label: {q(label)}",
           f"      description: {q(desc)}",
           "      options:"]
    for e in items:
        prefix = f"{e['id']} — " + (f"{e['feature']}: " if e["feature"] else "")
        out.append(f"        - label: {q(prefix + e['text'])}")
    out.append("")
    return out


def project_form(project: dict, entries: list[dict]) -> str:
    pid, title, num = project["id"], project["title"], project["id"][1:]
    feats = [e for e in entries if e["kind"] == "feature"]
    stories = [e for e in entries if e["kind"] == "story"]

    lines = [
        HEADER.rstrip(),
        f"name: {q(f'{pid} attempt — {title}')}",
        "description: " + q(
            f"Declare an attempt at ERI project {num} and claim the backlog IDs "
            f"it will cover. Several teams may attempt {pid}; attempts are "
            "compared, never merged into each other."),
        f"title: {q(f'[{pid}] ')}",
        "labels:",
        f"  - {q('attempt')}",
        f"  - {q('project:' + pid.lower())}",
        "body:",
        "  - type: markdown",
        "    attributes:",
        "      value: " + q(
            f"### {pid}: {title}\n\n"
            f"ERI's own words for this project are in `{SOURCE_DOC}`, under "
            f"\"Project {num}: {title}\". Where this form and that document "
            "disagree, the document wins and this form is a bug.\n\n"
            "Tick the requirements this attempt will cover. Claim what you "
            "intend to finish, not everything that looks interesting: an "
            "attempt claiming six features and landing two is harder to judge "
            "than one claiming two and landing two."),
        "",
        "  - type: input",
        "    id: team",
        "    attributes:",
        "      label: " + q("Team or attempt name"),
        "      description: " + q(
            f"Goes in your branch name: attempt/<team>/{pid.lower()}-<short-thing>"),
        "    validations:",
        "      required: true",
        "",
        "  - type: textarea",
        "    id: outcome",
        "    attributes:",
        "      label: " + q("What a person will be able to do"),
        "      description: " + q(
            "One or two plain sentences, about the person using it. No "
            "architecture, no stack."),
        "    validations:",
        "      required: true",
        "",
    ]
    lines += checkbox_block(
        "features", f"Core features claimed ({len(feats)} available)",
        "ERI's core-features table for this project, verbatim. The ID before "
        "the dash is what your pull request and your tests cite.", feats)
    lines += checkbox_block(
        "stories", f"User stories claimed ({len(stories)} available)",
        "ERI's user stories for this project, verbatim.", stories)
    lines += [
        "  - type: input",
        "    id: spec_ids",
        "    attributes:",
        "      label: " + q("Frozen-spec IDs this attempt answers (optional)"),
        "      description: " + q(
            f"From challenges/{pid.lower()}-*/spec/acceptance.md, if it exists "
            "yet: MVP steps, accessibility requirements, success criteria, "
            "prohibitions. These are what the attempt is CHECKED against, as "
            "opposed to the backlog IDs above, which are what it claims to "
            "build. Both belong in the pull request body."),
        "      placeholder: " + q(f"{pid}-M3, {pid}-A4, {pid}-S1"),
        "",
        "  - type: textarea",
        "    id: non_text",
        "    attributes:",
        "      label: " + q("Alternatives to typing, and to reading"),
        "      description: " + q(
            "All four of ERI's projects require an alternative to typed input, "
            "and text alternatives for anything that is not text. Say what "
            "yours will be: pictures, audio, predefined choices, transcripts, "
            "captions."),
        "    validations:",
        "      required: true",
        "",
        "  - type: checkboxes",
        "    id: prohibitions",
        "    attributes:",
        "      label: " + q("ERI's prohibitions"),
        "      description: " + q(
            "ERI wrote these. They are not negotiable for a prototype, and "
            "they are not a reviewer's job to discover on the last afternoon."),
        "      options:",
    ]
    for p in PROHIBITIONS:
        lines += [f"        - label: {q(p)}", "          required: true"]
    lines += [
        "",
        "  - type: textarea",
        "    id: known_hard",
        "    attributes:",
        "      label: " + q("Anything you already know will be hard"),
        "      description: " + q(
            "Optional, and the most useful box on this form. Naming the risk "
            "up front is how your pull request gets read fairly."),
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def defect_form() -> str:
    lines = [
        HEADER.rstrip(),
        "name: " + q("Defect in the spec or a conformance test"),
        "description: " + q(
            "A PRD, the backlog, a conformance test or a repo gate is wrong, "
            "contradicts ERI's problem statements, or passes something it "
            "should fail."),
        "title: " + q("[defect] "),
        "labels:",
        f"  - {q('defect')}",
        "body:",
        "  - type: markdown",
        "    attributes:",
        "      value: " + q(
            "Teams find these. The spec is frozen for the event, which makes a "
            "defect in it everyone's problem at once rather than one team's, "
            "so report it here instead of quietly working around it in your "
            "own folder.\n\n"
            "**A test that PASSES something it should fail is the worse half "
            "of this form.** A gate that cannot go red is not a gate, and "
            "every attempt it green-lit is unverified."),
        "",
        "  - type: dropdown",
        "    id: surface",
        "    attributes:",
        "      label: " + q("Where is the defect"),
        "      options:",
    ]
    for opt in [
        f"ERI problem statements ({SOURCE_DOC})",
        "Generated backlog (docs/eri-backlog.md or .json)",
        "A PRD in wiki/prds/",
        "A conformance test inside a project folder",
        "A repo gate (tools/ or .github/workflows/)",
        "An issue form or the pull request template",
        "Something else, named below",
    ]:
        lines.append(f"        - {q(opt)}")
    lines += [
        "    validations:",
        "      required: true",
        "",
        "  - type: dropdown",
        "    id: direction",
        "    attributes:",
        "      label: " + q("Which way is it wrong"),
        "      options:",
    ]
    for opt in [
        "It fails work that is correct (a false red)",
        "It passes work that is wrong (a false green)",
        "It contradicts ERI's problem statements",
        "It is ambiguous: two teams read it two ways",
        "It cannot run at all",
    ]:
        lines.append(f"        - {q(opt)}")
    lines += [
        "    validations:",
        "      required: true",
        "",
        "  - type: input",
        "    id: location",
        "    attributes:",
        "      label: " + q("File, and line or heading"),
        "      placeholder: " + q("challenges/p2-.../features/tasks.feature:41"),
        "    validations:",
        "      required: true",
        "",
        "  - type: input",
        "    id: backlog_ids",
        "    attributes:",
        "      label: " + q("Backlog IDs affected"),
        "      description: " + q(
            "From docs/eri-backlog.md, if any. Blank if the defect is not tied "
            "to a requirement."),
        "      placeholder: " + q("P3-F5, P3-US2"),
        "",
        "  - type: textarea",
        "    id: evidence",
        "    attributes:",
        "      label: " + q("The command, and what it actually printed"),
        "      description: " + q(
            "Paste the real output. A described failure cannot be reproduced "
            "by the person who has to fix it, and during a one-day event that "
            "is the difference between fixed and not."),
        "      render: " + q("shell"),
        "    validations:",
        "      required: true",
        "",
        "  - type: textarea",
        "    id: expected",
        "    attributes:",
        "      label: " + q("What ERI's document says should happen"),
        "      description: " + q(
            "Quote it. The problem statements are the source of truth, so a "
            "defect report that cites them is settled in one reading."),
        "    validations:",
        "      required: true",
        "",
        "  - type: checkboxes",
        "    id: scope",
        "    attributes:",
        "      label: " + q("Before you file"),
        "      options:",
        "        - label: " + q(
            "This affects everyone attempting the project, not only my branch"),
        "        - label: " + q(
            "I checked ERI's problem statements rather than only the PRD"),
        "        - label: " + q(
            "I can write a failing test that proves it (say so below if you did)"),
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def config_yml(slug: str) -> str:
    base = f"https://github.com/{slug}" if slug else ""
    lines = [
        "# Generated by tools/gen_issue_forms.py.",
        "#",
        "# The URLs below are DERIVED from $GITHUB_REPOSITORY or the `origin`",
        "# remote at generation time, never hardcoded, so a generated copy of",
        "# this template re-derives its own by running the generator again.",
        "",
        "# An attempt should use a project form so its claimed backlog IDs are",
        "# machine-readable. A blank issue is still allowed for everything",
        "# else: a question, a logistics note, a thing nobody has a form for.",
        "blank_issues_enabled: true",
    ]
    if not base:
        lines += [
            "",
            "# No owner/repository could be derived here, so no contact links",
            "# were written. Run `python3 tools/gen_issue_forms.py` inside a",
            "# clone that has an `origin` remote, or with GITHUB_REPOSITORY set.",
            "contact_links: []",
        ]
        return "\n".join(lines) + "\n"
    links = [
        ("ERI's problem statements (the source of truth)",
         f"{base}/blob/HEAD/{SOURCE_DOC}",
         "The four projects in ERI's own words: features, user stories, MVP, "
         "accessibility requirements, what is out of scope, and what is "
         "prohibited. Where anything else disagrees, this wins."),
        ("The backlog, with the IDs an attempt claims",
         f"{base}/blob/HEAD/docs/eri-backlog.md",
         "Every core feature and user story with a stable ID. Generated from "
         "the problem statements."),
        ("How attempts work here",
         f"{base}/blob/HEAD/CONTRIBUTING.md",
         "Branch naming, one attempt per pull request, how two attempts at the "
         "same problem are compared rather than merged, and the definition of "
         "done."),
    ]
    lines.append("contact_links:")
    for name, url, about in links:
        lines += [f"  - name: {q(name)}",
                  f"    url: {q(url)}",
                  f"    about: {q(about)}"]
    return "\n".join(lines) + "\n"


def build() -> dict[str, str]:
    """path -> content, for everything this generator owns except config.yml."""
    backlog = json.load(open(BACKLOG, encoding="utf-8"))
    out: dict[str, str] = {}
    for project in backlog["projects"]:
        entries = [e for e in backlog["entries"] if e["project"] == project["id"]]
        if not entries:
            continue
        slug = re.sub(r"[^a-z0-9]+", "-", project["title"].lower()).strip("-")
        name = f"{project['id'].lower()}-{slug}.yml"
        out[os.path.join(OUTDIR, name)] = project_form(project, entries)
    out[os.path.join(OUTDIR, "spec-or-test-defect.yml")] = defect_form()
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the generated forms on disk are stale "
                         "(config.yml is excluded: its content depends on the "
                         "repository's location)")
    args = ap.parse_args(argv)

    os.chdir(REPO)
    if not os.path.exists(BACKLOG):
        print(f"ERROR: {BACKLOG} is missing, so no issue form can list a "
              "claimable backlog ID.", file=sys.stderr)
        print("Run: python3 tools/gen_backlog.py", file=sys.stderr)
        return 2

    want = build()
    if args.check:
        stale = [p for p, text in sorted(want.items())
                 if not os.path.exists(p)
                 or open(p, encoding="utf-8").read() != text]
        if stale:
            for p in stale:
                print(f"STALE: {p} is not what tools/gen_issue_forms.py "
                      f"produces from {BACKLOG}", file=sys.stderr)
            print("Run: python3 tools/gen_issue_forms.py", file=sys.stderr)
            return 1
        print(f"issue forms ok ({len(want)} files current; {CONFIG} not checked "
              "-- its URLs are derived from this repository's location)")
        return 0

    os.makedirs(OUTDIR, exist_ok=True)
    for path, text in sorted(want.items()):
        open(path, "w", encoding="utf-8").write(text)
        print(f"  wrote {path}")

    slug = repo_slug()
    open(CONFIG, "w", encoding="utf-8").write(config_yml(slug))
    print(f"  wrote {CONFIG} (owner/repo derived as "
          f"{slug or 'NOTHING -- no contact links written'})")
    print(f"wrote {len(want) + 1} files into {OUTDIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
