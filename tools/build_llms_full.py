#!/usr/bin/env python3
"""Concatenate AGENTS.md + every wiki page into llms-full.txt (re-run after editing the wiki)."""
import glob, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
os.chdir(root)
files = ["AGENTS.md", "wiki/README.md"] + sorted(
    f for f in glob.glob("wiki/**/*.md", recursive=True) if f != "wiki/README.md") + ["agents/README.md", "data/README.md"]
with open("llms-full.txt", "w", encoding="utf-8") as out:
    out.write("# Hackreation x ERI: full wiki\n\nGenerated by tools/build_llms_full.py. Source files are authoritative.\n")
    for f in files:
        out.write(f"\n\n<!-- FILE: {f} -->\n\n" + open(f, encoding="utf-8").read())
print(f"llms-full.txt: {len(files)} files, {os.path.getsize('llms-full.txt')//1024} KB")
